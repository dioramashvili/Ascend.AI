    api_request = EvaluationRequest(**frontend_payload)
    print(f"✅ API Request Validated: {api_request.model_dump_json(indent=2)}")

    # 2. Validating arguments from an LLM function call (Section 3 model)
    print("\n2. Validating LLM-generated arguments:")
    llm_args = {
        "career_title": "software engineer",
        "user_answer": "I choose to refactor the code.",
        "session_id": "ad1e93c7-6fbb-46fa-8a3b-dcbb6f308a90"
        # 'task_mode' is omitted, will use default 'async'
    }
    validated_args = EvaluateResponseArgs(**llm_args)
    print(f"✅ LLM Arguments Validated: {validated_args.model_dump_json(indent=2)}")

    # 3. Constructing a successful function response for the LLM (Section 4 model)
    print("\n3. Constructing a successful Function Response:")
    func_response_payload = FunctionResponse(
        status=FunctionStatusEnum.SUCCESS,
        data=EvaluationResultData(
            feedback="Refactoring is a proactive choice that pays off long-term.",
            score=9
        )
    )
    print(f"✅ Function Response (Success): {func_response_payload.model_dump_json(indent=2)}")

    # 4. Constructing an error function response for the LLM (Section 4 model)
    print("\n4. Constructing an error Function Response:")
    error_response_payload = FunctionResponse(
        status=FunctionStatusEnum.ERROR,
        error_code=ErrorCodeEnum.TASK_NOT_FOUND,
        error_message="No task found with this ID."
    )
    print(f"✅ Function Response (Error): {error_response_payload.model_dump_json(indent=2)}")
    
    print("\n" + "=" * 60)
    print("✅ All examples completed successfully!")
    print("=" * 60)